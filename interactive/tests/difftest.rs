//! Differential testing of DDIR: random, well-typed lambda programs over random update streams,
//! checked against oracles that need no reference implementation.
//!
//! **What a seed generates.** One case, the same every time for the same seed: a program over up
//! to six declared inputs (int pairs, `(int ; int)`, a list key, a declared sum, floats), with a
//! few `let`s of `map`, `value`, `filter`, `flatmap`, `join`, `negate`, concat and difference,
//! `arrange`, the reductions (`distinct`, `count`, `min`, `collect`, `reduce` by a lambda),
//! `delay` and `join_function`, and small iterative scopes (reachability or label propagation,
//! sometimes nested); and its feeds, 3 to 30 epochs of inserts and retractions over small values,
//! so that keys collide, sometimes with ints of every storage width, or one big epoch.
//!
//! **Oracles.** Each compares the program's exports after every epoch with another way of
//! computing them:
//! - `workers`: two to five workers, against one.
//! - `scratch`: the accumulated input evaluated in one go, against the incremental run.
//! - `optimize`: the program unoptimized.
//! - `delta`: every `join` written as a delta join (two `half_join`s, delayed to their data times).
//! - `ahead`: every epoch's rows fed up front, each at its future time.
//! - `split`: the program cut in two, a producer publishing what a consumer imports, as containers
//!   or arrangements.
//! - `bind`: the consumer's inputs bound to the producer's published traces instead.
//! - `reinstall`: the consumer dropped, and installed again later.
//!
//! Until imports read their traces as of their install, a consumer is installed with its producer,
//! and `reinstall` does not run: see [`LATE_INSTALLS`].
//! - `explain`: every row of the first export is regenerated by its explanation alone (see
//!   `Case::explainable` for the cases it skips).
//!
//! On one worker every snapshot also survives a binary frame and a feed-text round trip, an
//! export's tapped changes sum to its contents, and a keyed peek is its contents at the key.
//!
//! **Running.** The sweep is `#[ignore]`d:
//! ```text
//! DIFFTEST_SEED=0 DIFFTEST_CASES=1000 cargo test --release -p interactive --test difftest -- --ignored --nocapture
//! ```
//! - `DIFFTEST_ORACLES=workers,delta` runs only those oracles; the default is all of them.
//! - `DIFFTEST_OUT=<dir>` keeps the case being run in `current.txt`, and each failure in
//!   `finding-<seed>.txt`.
//! - A failure is minimized (exports, epochs, rows and ops) and printed: the program, its feeds per
//!   epoch, the rows that disagree, and the commands that replay it. `DIFFTEST_SEED=<seed>
//!   DIFFTEST_CASES=1` reproduces any case, with the programs `split`, `bind` and `reinstall`
//!   derive from it; `DIFFTEST_CASE_FILE=<file>` checks a case as a failure prints it, edited by
//!   hand if you like (the derived programs aside).
//! - A case that makes no progress for two minutes stops the sweep, naming its seed.

